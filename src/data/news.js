export function getNewsPosts() {
  return [...newsPosts].sort((a, b) => new Date(b.date) - new Date(a.date));
}

export function getNewsSlugs() {
  return newsPosts.map((post) => post.slug);
}

export function getNewsBySlug(slug) {
  return newsPosts.find((post) => post.slug === slug);
}

export function getNewsTags() {
  return [...new Set(newsPosts.flatMap((post) => post.tags))].sort((a, b) =>
    a.localeCompare(b)
  );
}

export function formatNewsDate(date, lang = 'es') {
  return new Intl.DateTimeFormat(
    lang === 'en' ? 'en-GB' : lang === 'de' ? 'de-DE' : 'es-ES',
    {
      day: 'numeric',
      month: 'long',
      year: 'numeric',
    }
  ).format(new Date(date));
}
